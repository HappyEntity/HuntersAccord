using System.Text;
using HuntersAccord.Core.Settings;

namespace HuntersAccord.Core.Input;

/// <summary>Who owns the input right now: the player character or the game's UI (menus, messages, title).</summary>
public enum InputContext
{
    Gameplay,
    Interface,
}

/// <summary>
/// shadPS4 input config for Bloodborne (<c>user/input_config/&lt;TITLE_ID&gt;.ini</c>).
/// With the Hunters' Accord mod the keyboard and mouse are handled by the mod itself, so shadPS4 only passes the gamepad
/// through. Without the mod (troubleshooting) a basic shadPS4 keyboard layout is written instead.
/// </summary>
public static class KbmLayout
{
    private static readonly string[] ShadPs4Keyboard =
    [
        "axis_left_y_minus = w", "axis_left_y_plus = s", "axis_left_x_minus = a", "axis_left_x_plus = d",
        "axis_right_y_minus = i", "axis_right_y_plus = k", "axis_right_x_minus = j", "axis_right_x_plus = l",
        "r1 = leftbutton", "r2 = lshift, leftbutton", "l2 = rightbutton", "l1 = lshift, rightbutton",
        "r3 = middlebutton", "r3 = q", "circle = space", "l3 = lctrl",
        "cross = e", "cross = enter", "circle = backspace", "triangle = r", "square = f",
        "pad_up = up", "pad_down = down", "pad_left = left", "pad_right = right",
        "options = escape", "touchpad_center = tab",
    ];

    /// <param name="withMod">Keyboard and mouse are the mod's; without it shadPS4 gets a basic keyboard layout.</param>
    /// <param name="gamepad">The player's gamepad (Settings → Controls); null = every button as it is.</param>
    public static string Render(bool withMod, GamepadSettings? gamepad = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Hunters' Accord (Seamless Co-op for Bloodborne) — changes here are overwritten.");
        sb.AppendLine("# The gamepad is set up in the Hunters' Accord launcher: Settings > Controls.");
        if (withMod)
        {
            sb.AppendLine("# Keyboard & mouse are handled by the Hunters' Accord mod; set them up in-game: System > Controls.");
        }
        else
        {
            sb.AppendLine("# Started without the Hunters' Accord mod: basic shadPS4 keyboard layout.");
            foreach (var line in ShadPs4Keyboard) sb.AppendLine(line);
        }
        sb.AppendLine();
        sb.AppendLine(ControllerHeader);
        foreach (var line in PadButtons.Render(gamepad ?? new GamepadSettings())) sb.AppendLine(line);
        return sb.ToString();
    }

    private const string ControllerHeader = "# Controller";

    public static string ConfigPath(string shadPs4UserDir, string titleId) =>
        Path.Combine(shadPs4UserDir, "input_config", titleId + ".ini");

    public static void Write(string shadPs4UserDir, string titleId, bool withMod, GamepadSettings? gamepad = null)
    {
        var path = ConfigPath(shadPs4UserDir, titleId);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, Render(withMod, gamepad));
    }

    /// <summary>Gives shadPS4 its keyboard layout back in a config written for the mod, keeping the player's gamepad part (the mod's fallback).</summary>
    public static void AddShadPs4Keyboard(string shadPs4UserDir, string titleId)
    {
        var path = ConfigPath(shadPs4UserDir, titleId);
        var existing = File.Exists(path) ? File.ReadAllLines(path) : [];
        var controller = Array.IndexOf(existing, ControllerHeader);
        var sb = new StringBuilder(Render(withMod: false));
        if (controller >= 0)
        {
            // The freshly rendered default gamepad part goes; the player's one stays.
            sb.Length = sb.ToString().IndexOf(ControllerHeader, StringComparison.Ordinal);
            foreach (var line in existing[controller..]) sb.AppendLine(line);
        }
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, sb.ToString());
    }
}
