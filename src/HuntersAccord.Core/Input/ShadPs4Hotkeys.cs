using System.Text;
using HuntersAccord.Core.Settings;

namespace HuntersAccord.Core.Input;

/// <summary>A shadPS4 hotkey kept for the player: its config name, keys (Hunters' Accord key names) and action (text key suffix).</summary>
public sealed record ShadPs4Hotkey(string Name, string Keys, string Action)
{
    public string MainKey => Keys.Split('+')[^1];
}

/// <summary>
/// shadPS4's own hotkeys (<c>user/input_config/global.ini</c>). shadPS4 adds any hotkey missing from the file with its default key, so the ones
/// Hunters' Accord does not want are written bound to <see cref="NoKey"/> ("unmapped"; an empty value is skipped as "Invalid format"): those
/// that change how the mouse drives the pad, add or remove players, reload the input config or open shadPS4's overlays.
/// The useful ones stay, unless the mod's controls use their key.
/// </summary>
public static class ShadPs4Hotkeys
{
    /// <summary>shadPS4's input-config key name for "no key".</summary>
    public const string NoKey = "unmapped";

    public static IReadOnlyList<ShadPs4Hotkey> Kept { get; } =
    [
        new("hotkey_fullscreen", "F11", "Fullscreen"),
        new("hotkey_show_fps", "F10", "Fps"),
        new("hotkey_pause", "F9", "Pause"),
        new("hotkey_screenshot_with_overlays", "LAlt+F12", "Screenshot"),
        new("hotkey_capture_frame", "F12", "CaptureFrame"),
        new("hotkey_quit", "LCtrl+LShift+End", "Quit"),
        new("hotkey_volume_up", "KpPlus", "VolumeUp"),
        new("hotkey_volume_down", "KpMinus", "VolumeDown"),
    ];

    public static IReadOnlyList<string> Disabled { get; } =
    [
        "hotkey_reload_inputs", "hotkey_toggle_mouse_to_joystick", "hotkey_toggle_mouse_to_gyro",
        "hotkey_toggle_mouse_to_touchpad", "hotkey_add_virtual_user", "hotkey_remove_virtual_user",
        "hotkey_emulator_settings", "hotkey_toggle_friends",
    ];

    /// <summary>Every key the mod reacts to: both contexts' bindings, the debug keys and the backup key.</summary>
    public static IReadOnlySet<string> ModKeys(GameSettings settings) =>
        (settings.KeyboardMouse ? settings.EffectiveBindings : []).SelectMany(b => b.KeyList)
            .Concat(settings.DebugKeys.Values.Append(settings.SaveBackupKey).SelectMany(k => k.Split('+')))
            .Select(k => k.Trim())
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

    public static bool IsTaken(ShadPs4Hotkey hotkey, IReadOnlySet<string> modKeys) => modKeys.Contains(hotkey.MainKey);

    public static string Render(IReadOnlySet<string> modKeys, IReadOnlyCollection<string>? turnedOff = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Hunters' Accord (Seamless Co-op for Bloodborne): changes here are overwritten.");
        sb.AppendLine($"# A hotkey on \"{NoKey}\" is off (a missing one would get its default key back).");
        foreach (var hotkey in Kept)
            sb.AppendLine($"{hotkey.Name} = {(IsTaken(hotkey, modKeys) || turnedOff?.Contains(hotkey.Name) == true ? NoKey : ToShadPs4(hotkey.Keys))}");
        foreach (var name in Disabled)
            sb.AppendLine($"{name} = {NoKey}");
        return sb.ToString();
    }

    public static string ConfigPath(string shadPs4UserDir) => Path.Combine(shadPs4UserDir, "input_config", "global.ini");

    /// <param name="modKeys">Keys of the mod's controls (<see cref="ModKeys"/>); empty when the game starts without the mod.</param>
    /// <param name="turnedOff">Kept hotkeys the player turned off, by config name.</param>
    public static void Write(string shadPs4UserDir, IReadOnlySet<string> modKeys, IReadOnlyCollection<string>? turnedOff = null)
    {
        var path = ConfigPath(shadPs4UserDir);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, Render(modKeys, turnedOff));
    }

    /// <summary>"LCtrl+LShift+End" → "lctrl, lshift, end" (shadPS4 key names are Hunters' Accord's in lower case for these keys).</summary>
    private static string ToShadPs4(string keys) =>
        string.Join(", ", keys.Split('+').Select(k => k.ToLowerInvariant()));
}
